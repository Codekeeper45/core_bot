'use strict';
// «Тихий стаб» — самонарратив, который модель иногда выдаёт по расписанию вместо
// настоящего ПУСТОГО ответа: «Пустой ответ — напоминание отправлено», «Проверено»,
// «Всё ок» и т.п. На scheduled-прогонах такие сообщения боссу не нужны — глушим.
// Консервативно: матчим только явный самонарратив, не реальные короткие напоминания.

const FULL_STUBS = new Set([
  'проверено', 'проверка завершена', 'все ок', 'все в порядке', 'все хорошо',
  'готово', 'сделано', 'выполнено', 'без изменений', 'нет изменений',
  'ничего', 'ничего не требуется', 'ничего не нужно', 'ок', 'окей',
  'напоминание отправлено', 'отправлено', 'отправлено сотруднику',
]);

function clean(text) {
  return String(text || '')
    .replace(/ё/gi, 'е')
    .replace(/[^\p{L}\p{N}\s]/gu, ' ') // убрать эмодзи/пунктуацию (символы — не буквы/цифры)
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
}

function isSilentStub(text) {
  const t = clean(text);
  if (!t) return false; // настоящую пустоту обрабатывает вызывающий отдельно
  // Утечка инструкции «верни пустой ответ» в любом виде (\w не матчит кириллицу — используем \S).
  if (/пуст\S* ответ|ответ пуст\S*/.test(t)) return true;
  // Явные маркеры отправки напоминания сотруднику.
  if (t.includes('напоминание отправлено') || t.includes('отправлено сотруднику')) return true;
  // Короткая отписка целиком = стаб.
  if (FULL_STUBS.has(t)) return true;
  return false;
}

module.exports = { isSilentStub };
